export function t(key, vars = {}) {
  const text = dict[state.lang]?.[key] ?? dict.sq[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

// Zgjedh tekstin sipas gjuhës nga një objekt { sq, en }
export const tl = (obj) => obj[state.lang] ?? obj.sq;

// Datat: disa shfletues nuk kanë të dhëna për gjuhën shqipe në Intl, prandaj i kemi vetë emrat
const SQ_DAYS = ["Die", "Hën", "Mar", "Mër", "Enj", "Pre", "Sht"];
const SQ_MONTHS = ["janar", "shkurt", "mars", "prill", "maj", "qershor", "korrik", "gusht", "shtator", "tetor", "nëntor", "dhjetor"];
const hasNativeSq = Intl.DateTimeFormat.supportedLocalesOf(["sq"]).length > 0;
const OPTIONS = {
  short: { day: "numeric", month: "numeric", year: "numeric" },
  dayMonth: { weekday: "short", day: "numeric", month: "short" },
  weekday: { weekday: "short" },
  month: { month: "short" },
  monthLong: { month: "long" },
};

export function fmtDate(date, style = "short") {
  if (state.lang !== "sq" || hasNativeSq) {
    return date.toLocaleDateString(state.lang === "sq" ? "sq-AL" : "en-GB", OPTIONS[style]);
  }
  const month = SQ_MONTHS[date.getMonth()];
  return {
    short: `${date.getDate()}.${date.getMonth() + 1}.${date.getFullYear()}`,
    dayMonth: `${SQ_DAYS[date.getDay()]}, ${date.getDate()} ${month.slice(0, 3)}`,
    weekday: SQ_DAYS[date.getDay()],
    month: month.slice(0, 3),
    monthLong: month,
  }[style];
}
